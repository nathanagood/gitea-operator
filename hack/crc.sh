#!/usr/bin/env bash
# Build the operator image, push it to the image registry inside an OpenShift
# Local (CRC) cluster, and run it there. Normally called through the Makefile:
#
#   make crc-push      build and push the image only
#   make crc-deploy    push, then point the running operator at the new image
#   make crc-install   push, then apply the whole operator (namespace, CRDs,
#                      RBAC, deployment); use this on a fresh cluster or after
#                      RBAC or CRD changes
#
# The Makefile builds ./manager first; the Dockerfile copies that binary in.
#
# Settings (environment variables):
#   CRC_TAG               image tag (default: dev-<timestamp>, unique per run)
#   CRC_WATCH_NAMESPACES  namespaces the operator watches, for crc-install
#                         (default: default,cert-manager,gitea-test)
#   CRC_API               expected API server (default: https://api.crc.testing:6443)
#   CRC_REGISTRY          registry route (default: default-route-openshift-image-registry.apps-crc.testing)
#   CONTAINER_TOOL        default: podman
#
# Requires `oc` logged in to CRC as a cluster admin (for example kubeadmin).
set -euo pipefail

CRC_API="${CRC_API:-https://api.crc.testing:6443}"
CRC_REGISTRY="${CRC_REGISTRY:-default-route-openshift-image-registry.apps-crc.testing}"
CRC_TAG="${CRC_TAG:-dev-$(date +%Y%m%d%H%M%S)}"
CRC_WATCH_NAMESPACES="${CRC_WATCH_NAMESPACES:-default,cert-manager,gitea-test}"
CONTAINER_TOOL="${CONTAINER_TOOL:-podman}"

# The install namespace and deployment name come from config/default
# (namespace and namePrefix). The image is pushed to the same namespace, so the
# deployment can pull it without extra grants.
NAMESPACE=gitea-operator-system
DEPLOYMENT=gitea-operator-controller-manager
INTERNAL_REGISTRY=image-registry.openshift-image-registry.svc:5000

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PUSH_IMAGE="${CRC_REGISTRY}/${NAMESPACE}/gitea-operator:${CRC_TAG}"
PULL_IMAGE="${INTERNAL_REGISTRY}/${NAMESPACE}/gitea-operator:${CRC_TAG}"

die() {
	echo "error: $*" >&2
	exit 1
}

# require_crc stops unless oc points at the CRC cluster, so an image or
# deployment change never lands on another cluster by accident.
require_crc() {
	local server
	server="$(oc whoami --show-server 2>/dev/null)" ||
		die "oc is not logged in. Log in to CRC first: oc login -u kubeadmin ${CRC_API}"
	[[ "${server}" == "${CRC_API}" ]] ||
		die "oc points at ${server}, not ${CRC_API}. Switch first, for example: oc config use-context crc-admin"
}

# registry_login creates the image namespace if needed and logs the container
# tool in to the registry route with the current oc token. The route uses a
# self-signed certificate, hence --tls-verify=false.
registry_login() {
	oc get namespace "${NAMESPACE}" >/dev/null 2>&1 || oc create namespace "${NAMESPACE}"
	oc whoami -t | "${CONTAINER_TOOL}" login --tls-verify=false --password-stdin \
		-u "$(oc whoami)" "${CRC_REGISTRY}" >/dev/null
}

push() {
	[[ -x "${ROOT}/manager" ]] || die "${ROOT}/manager is missing; build it with 'make manager'"
	require_crc
	registry_login
	"${CONTAINER_TOOL}" build -t "${PUSH_IMAGE}" "${ROOT}"
	"${CONTAINER_TOOL}" push --tls-verify=false "${PUSH_IMAGE}"
	echo "Pushed ${PUSH_IMAGE}"
	echo "In-cluster image: ${PULL_IMAGE}"
}

wait_for_rollout() {
	oc rollout status "deployment/${DEPLOYMENT}" -n "${NAMESPACE}" --timeout=180s
}

deploy() {
	push
	oc get "deployment/${DEPLOYMENT}" -n "${NAMESPACE}" >/dev/null 2>&1 ||
		die "deployment ${NAMESPACE}/${DEPLOYMENT} not found; run 'make crc-install' first"
	oc set image "deployment/${DEPLOYMENT}" -n "${NAMESPACE}" "manager=${PULL_IMAGE}"
	wait_for_rollout
}

# install renders config/default through a generated overlay that sets the
# image and WATCH_NAMESPACES, and applies it server-side (the CRDs are too
# large for client-side apply's last-applied annotation).
install() {
	push
	local overlay="${ROOT}/bin/crc-overlay"
	mkdir -p "${overlay}"
	cat >"${overlay}/kustomization.yaml" <<EOF
# Generated by hack/crc.sh; do not edit.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
- ../../config/default
patches:
- patch: |-
    apiVersion: apps/v1
    kind: Deployment
    metadata:
      name: ${DEPLOYMENT}
      namespace: ${NAMESPACE}
    spec:
      template:
        spec:
          containers:
          - name: manager
            image: ${PULL_IMAGE}
            env:
            - name: WATCH_NAMESPACES
              value: "${CRC_WATCH_NAMESPACES}"
EOF
	oc kustomize "${overlay}" | oc apply --server-side --force-conflicts -f -
	wait_for_rollout
}

usage() {
	sed -n '2,23p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
	exit "${1:-0}"
}

case "${1:-}" in
push) push ;;
deploy) deploy ;;
install) install ;;
-h | --help | help) usage 0 ;;
*) usage 1 ;;
esac
